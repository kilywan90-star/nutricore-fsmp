// ============ UTILITY FUNCTIONS ============
function rand(min, max) { return Math.floor(Math.random() * (max - min + 1)) + min; }
function randFloat(min, max, decimals = 6) { return parseFloat((Math.random() * (max - min) + min).toFixed(decimals)); }
function pick(arr) { return arr[Math.floor(Math.random() * arr.length)]; }
function pickN(arr, n) { const s = [...arr]; for (let i = s.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [s[i], s[j]] = [s[j], s[i]]; } return s.slice(0, Math.min(n, s.length)); }
function genPhone(code) { return `${code}-${rand(10000000, 99999999)}`; }

function genPrivacyLevel() {
  const r = Math.random();
  if (r < 0.15) return 'L1';
  if (r < 0.45) return 'L2';
  if (r < 0.75) return 'L3';
  return 'L4';
}

function genPrivateRoom(level) {
  if (level === 'L1') return { min: null, max: null, count: null };
  if (level === 'L2') return { min: rand(4, 6), max: rand(10, 16), count: rand(1, 5) };
  if (level === 'L3') return { min: rand(6, 10), max: rand(16, 30), count: rand(5, 12) };
  return { min: rand(10, 20), max: rand(30, 60), count: rand(12, 30) };
}

function genStories(storyPool) { return [pick(storyPool)]; }

