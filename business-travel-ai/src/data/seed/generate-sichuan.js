function generateCity(config, minPerDistrict) {
  const restaurants = [];
  const storyIdx = {};
  for (const [district, _] of Object.entries(config.districts)) {
    storyIdx[district] = 0;
    for (let i = 0; i < minPerDistrict; i++) {
      const r = generateRestaurant(district, config, i);
      // Rotate through stories so each district gets variety
      const allStories = [...config.storyPool, ...(config.extraStoryPools || [])];
      r.stories = [allStories[(storyIdx[district] + i) % allStories.length]];
      restaurants.push(r);
    }
  }
  return { city: config.name, restaurants };
}

